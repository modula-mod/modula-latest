import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = rel => readFileSync(path.join(root, rel), 'utf8')

const hub = read('src/features/modules/screens/ProductHubMarketplaceScreen.tsx')
const header = read('src/features/modules/components/ProductHubHeader.tsx')
const hero = read('src/features/modules/components/presentation/ModuleEditorialHero.tsx')
const bleed = read('src/features/modules/components/presentation/EditorialBleedHero.tsx')
const split = read('src/features/modules/components/presentation/EditorialSplitHero.tsx')
const lab = read('src/platform/ui/dev/pvp-ui-1r-lab.tsx')
const coming = read('src/features/modules/components/presentation/ComingSoonEditorial.tsx')
const shelf = read('src/features/modules/components/presentation/ModuleIconShelf.tsx')
const browse = read('src/features/modules/components/presentation/ModuleBrowseGrid.tsx')
const canvas = read('src/features/modules/identity/marketplaceCanvas.ts')
const artwork = read('src/features/modules/identity/moduleArtwork.ts')

assert.match(lab, /pvp-ui-1r-direction-a/)
assert.match(lab, /pvp-ui-1r-direction-b/)
assert.match(lab, /pvp-ui-1r-direction-c/)
assert.match(hero, /size="editorial"/)
assert.match(hero, /LinearGradient/)
assert.match(bleed, /size="bleed"/)
assert.match(split, /size="split"/)
assert.match(coming, /Coming Soon/)
assert.doesNotMatch(coming, /opacity:\s*0\./)
assert.match(shelf, /module-icon-shelf/)
assert.match(browse, /module-browse-grid/)
assert.match(hub, /ModuleEditorialHero/)
assert.match(hub, /ModuleIconShelf/)
assert.match(hub, /ComingSoonEditorial/)
assert.match(hub, /ModuleBrowseGrid/)
assert.match(hub, /desktopSplit/)
assert.doesNotMatch(hub, /<ProductHubSegmentedControl/)
assert.match(header, /compact=\{!searchActive\}/)
assert.doesNotMatch(header, /Discover modules, tools and more/)
assert.match(canvas, /#000000/)
assert.match(artwork, /heroArtwork/)
assert.match(artwork, /editorialArtwork/)
assert.match(artwork, /moduleIcon/)
assert.doesNotMatch(hub, /\bfetch\s*\(/)
assert.doesNotMatch(hub, /downloads/)
assert.doesNotMatch(hub, /star rating/)
assert.match(read('src/features/modules/components/ProductHubLibraryControl.tsx'), /Discover/)
assert.match(read('src/features/modules/components/ProductHubLibraryControl.tsx'), /Installed/)
assert.match(read('src/features/modules/components/ProductHubLibraryControl.tsx'), /Updates/)

